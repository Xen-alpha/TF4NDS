const u16 letter[];

void  drawletter(u16 x, u16 y,char c) {
  int i,j;
  u16 col=31;

  for(i=0;i<8;i++) {
    for(j=0;j<8;j++) {
      if (c == 0x20) {
        //col = 0;
      } else {
        col = letter[ (j*720) + ( (c-0x21)*8 ) + i ];
        if(col!=0) Plot(x+i,y+j, RGB16(31,0,0));
      }
    }
  }

}

void  prints(u16 x, u16 y, char *s) {
//  char c;
  u16 cx = x;

  while(*s != 0) {
    drawletter(cx,y,*s++);
    cx += 8;
  }

}

void  printnum(u16 x, u16 y, s32 n) {
  u16 cx = x;
  u16 cnt=0;
  u16 diz=0;

  if (n < 0) {
    drawletter(cx,y,'-');
    n = -n;
    cx += 8;
  }

  while(n >= 100) {
    cnt++;
    n -= 100;
  }
  while(n >= 10) {
    diz++;
    n -= 10;
  }

  drawletter(cx,y, cnt+'0');
  cx += 8;
  drawletter(cx,y, diz+'0');
  cx += 8;
  drawletter(cx,y, n+'0');

}


